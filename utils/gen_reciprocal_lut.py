import math
import os

RTL_DIR = os.path.join(os.path.dirname(__file__), "..", "rtl")
FILENAME = "reciprocal_lut.v"


def entry_values(i):
    x_current = 1.0 + (float(i) / 256.0)
    x_next = 1.0 + (float(i + 1) / 256.0)
    base_val = int(round((1 << 30) / x_current))
    next_base_val = int(round((1 << 30) / x_next))
    slope_val = base_val - next_base_val
    return base_val, slope_val


def generate_sst1_lut():
    path = os.path.join(RTL_DIR, FILENAME)
    print(f"Generating {path}...")

    with open(path, "w", encoding="utf-8") as f:
        f.write("// reciprocal_lut.v\n")
        f.write("// Copyright (c) 2021-2026 Daniel Cliche\n")
        f.write("// SPDX-License-Identifier: MIT\n")
        f.write("//\n")
        f.write("// AUTO-GENERATED by utils/gen_reciprocal_lut.py — do not edit by hand.\n")
        f.write("//\n")
        f.write("// Piecewise linear reciprocal LUT for [1.0, 2.0).\n")
        f.write("//   lut_base(idx)  = round(2^30 / x)\n")
        f.write("//   lut_slope(idx) = lut_base(idx) - lut_base(idx + 1)\n")
        f.write("//\n")
        f.write("// Stored in inferred ECP5 block RAM ({slope, base} = 56 bits per entry).\n\n")

        f.write("module reciprocal_lut (\n")
        f.write("    input  wire        clk,\n")
        f.write("    input  wire        ce,\n")
        f.write("    input  wire        stall,\n")
        f.write("    input  wire [7:0]  idx,\n")
        f.write("    output reg  [31:0] base,\n")
        f.write("    output reg  [23:0] slope\n")
        f.write(");\n\n")

        f.write("    (* ram_style = \"block\" *) reg [55:0] mem [0:255];\n\n")
        f.write("    initial begin\n")

        for i in range(256):
            base_val, slope_val = entry_values(i)
            f.write(
                "        mem[8'd%d] = {24'h%06X, 32'h%08X};\n"
                % (i, slope_val, base_val)
            )

        f.write("    end\n\n")

        f.write("    always @(posedge clk) begin\n")
        f.write("        if (ce && !stall) begin\n")
        f.write("            base  <= mem[idx][31:0];\n")
        f.write("            slope <= mem[idx][55:32];\n")
        f.write("        end\n")
        f.write("    end\n\n")
        f.write("endmodule\n")

    print(f"Success! {FILENAME} generated.")


if __name__ == "__main__":
    generate_sst1_lut()
